#operations on string
#length of a string using len() function
full_name = 'CONGRATULATION'
print(len(full_name))
#indexing - getting a single value from a string SYNTAX: str_name[index_value]
print(full_name[4])
#slicing - getting multiple values from a string SYNTAX: str_name[start: end +1]
print(full_name[1:4])
print(full_name[0:4])
#concetanation - Joining 2 strings
fn = 'Congratulations'
ln = ' message '
print(fn+ln)